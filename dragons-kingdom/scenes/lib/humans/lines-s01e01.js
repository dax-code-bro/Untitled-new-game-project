/** Non-verbal takes (dlsrc 'kind': a cry, a gasp, a scream - no words): the face of the sound. */
export function nonverbalEmotion(kind) {
  const k = String(kind || '').toLowerCase();
  const e = {};
  const add = (m) => { for (const n in m) e[n] = Math.min(1, (e[n] || 0) + m[n]); };
  if (/scream|shriek/.test(k)) add({ fear: 0.85, pain: 0.35 });
  if (/\bcr(y|ies)\b|sob|wail/.test(k)) add({ pain: 0.7, fear: 0.25 });
  if (/gasp/.test(k)) add(/pain/.test(k) ? { pain: 0.8 } : { surprise: 0.4, fear: 0.3 });
  else if (/pain|hurt/.test(k)) add({ pain: 0.6 });
  if (/startl/.test(k)) add({ surprise: 0.3, fear: 0.3 });
  if (/sharp/.test(k)) add({ pain: 0.15 });
  if (!Object.keys(e).length) add({ surprise: 0.3 });
  return e;
}
