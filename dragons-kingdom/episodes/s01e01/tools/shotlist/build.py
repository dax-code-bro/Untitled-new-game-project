# twos segments (contiguous runs) for the render jobs
segs = []
for s in shots:
    if s['render'] != '3d':
        mode = s['render']
    else:
        mode = 'twos' if s['twos'] == 'ok' else 'ones'
    if segs and segs[-1]['mode'] == mode and segs[-1]['scene'] == s['scene']:
        segs[-1]['to'] = s['id']; segs[-1]['seconds'] += s['est_seconds']
    else:
        segs.append({'scene': s['scene'], 'mode': mode, 'from': s['id'], 'to': s['id'], 'seconds': s['est_seconds']})
render_cost['twos_segments'] = segs

