def rhalf(x):
    return math.floor(x * 2 + 0.5) / 2


def parse_inframe(s):
    out = []
    parts, depth, cur = [], 0, ''
    for ch in s:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ',' and depth == 0:
            parts.append(cur); cur = ''
        else:
            cur += ch
    parts.append(cur)
    for part in [p.strip() for p in parts if p.strip()]:
        # split on the LAST @ that is followed by a position token
        if '@' in part:
            name, pos = part.rsplit('@', 1)
        else:
            name, pos = part, ''
        out.append({'name': name.strip(), 'screen_pos': pos.strip()})
    return out


def speaker_in_frame(speaker, inframe):
    sp = speaker.lower()
    for f in inframe:
        n = f['name'].lower()
        if n.startswith(sp) or sp in n:
            return True
    return False


