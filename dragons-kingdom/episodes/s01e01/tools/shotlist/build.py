# ------------------------------------------------------------ speech timing model
RATE_DEFAULT = 2.6      # words per second (~156 wpm), natural conversational delivery
RATE_NARRATOR = 2.2     # ~132 wpm, "clear, restrained, sparse"
RATE_SOFT = 1.8         # whispered / quietly / low / through pain
MIN_LINE = 0.6          # even a one-word line occupies at least this
SENTENCE_PAUSE = 0.25   # extra pause per internal sentence break
TURN_GAP = 0.35         # cue pickup / reaction gap per line


def line_seconds(l):
    note = l['note'].lower()
    if l['speaker'] == 'NARRATOR':
        rate = RATE_NARRATOR
    elif any(k in note for k in ('whisper', 'quietly', 'low', 'through pain')):
        rate = RATE_SOFT
    else:
        rate = RATE_DEFAULT
    breaks = len(re.findall(r'[.?!—](?=\s+\S)', l['text']))
    return round(max(MIN_LINE, l['words'] / rate) + breaks * SENTENCE_PAUSE + TURN_GAP, 2)


