#!/usr/bin/env node
// Engine phase 4 (engine/DESIGN.md 3.7): stage an episode's shot list and write the spec files.
//   node engine/stager/write.mjs --episode t00 [--sets CLING_SQUARE] [--out DIR] [--check]
// Per set (one with a sheet in scenes/lib/director/sets/sheets/):
//   final/scenes/specs/<builder>.auto.js    GENERATED (header: stager version + input hash), never edited by hand
//   final/scenes/specs/<builder>.touch.js   the hand / LLM overlay: created once (empty), NEVER written again
//   final/scenes/specs/<builder>.spec.js    GENERATED: export default mergeSpecs(auto, touch)
//   final/scenes/<file>                     the set scene file (created once, the Episode 1 pattern)
//   final/stage-report.md + .json           per shot: template, score, tries, fixes, flags, unstaged phrases
// A set whose shots need the builder variant's props (places.json `variant`: the lute, the door...) is written as that
// variant (CLING_SQUARE -> CLING_SQUARE_2, registry `shotSet`). Episode 1 (s01e01) is hand-staged: it is refused unless
// --out names a scratch folder (its real specs are never overwritten). --check: exit 1 if a written file would change.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { dirs, episodeArg, episodeConfig, ROOT } from '../../scenes/lib/director/episode-paths.js';
import { SETS } from '../../scenes/lib/director/registry.js';
import { stageRows, loadPlaces, loadVerbs, castForStaging, STAGER_VERSION } from './stage.mjs';

const SHEETS = path.join(ROOT, 'scenes/lib/director/sets/sheets');
const relImport = (fromDir, file) => { const r = path.relative(fromDir, file).split(path.sep).join('/'); return r.startsWith('.') ? r : `./${r}`; };
const GEN = 'GENERATED by engine/stager/write.mjs';

/** stage `rows` of one episode; returns { files: Map(path -> text), reports } (nothing written) */
export function stageEpisode(ep, rows, { scenesDir, castLock = null, faces = 'avoid', holdOut = [], title = null } = {}) {
  const files = new Map(), reports = [];
  const specsDir = path.join(scenesDir, 'specs');
  const bySet = new Map();
  for (const r of rows) { if (!bySet.has(r.set)) bySet.set(r.set, []); bySet.get(r.set).push(r); }
  for (const [set, setRows] of [...bySet.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
    const sf = path.join(SHEETS, `${set}.json`);
    if (!fs.existsSync(sf)) { for (const r of setRows) reports.push({ id: r.id, template: null, flags: [`E_NO_SHEET ${set}`], score: 0, unstaged: [] }); continue; }
    const sheet = JSON.parse(fs.readFileSync(sf, 'utf8'));
    const places = loadPlaces(set);
    const lock = castLock || castForStaging(setRows, ep);
    const { spec, reports: rs } = stageRows(setRows, { sheet, places, verbs: loadVerbs(), castLock: lock, policy: { faces, holdOut } });
    reports.push(...rs);
    const setId = spec.set;
    const reg = SETS[setId];
    if (!reg?.builder) { for (const r of setRows) reports.find((x) => x.id === r.id).flags.push(`E_NO_BUILDER ${setId}`); continue; }
    const base = reg.builder;
    const body = JSON.stringify(spec, null, 1);
    const hash = crypto.createHash('sha1').update(JSON.stringify({ v: STAGER_VERSION, rows: setRows, sheet: sheet.generated ?? null, places })).digest('hex').slice(0, 12);
    files.set(path.join(specsDir, `${base}.auto.js`), `// ${GEN} (engine stager v${STAGER_VERSION}, input ${hash}) - DO NOT EDIT: put changes in ${base}.touch.js\n// ${ep} ${setId}: ${setRows.map((r) => r.id).join(' ')}\nexport default ${body};\n`);
    files.set(path.join(specsDir, `${base}.touch.js`), { once: true, text: `// Touch-up overlay for ${base}.auto.js (engine/DESIGN.md 3.7): { shots: { '<shot>': {...partial, deep-merged}, '<shot2>': { lock: true, ...whole } } }.\n// Written once by engine/stager/write.mjs and never again: edit freely.\nexport default { shots: {} };\n` });
    files.set(path.join(specsDir, `${base}.spec.js`), `// ${GEN}: the shot specs of ${setId} for ${ep} = the auto-stager's ${base}.auto.js + the touch-ups in ${base}.touch.js\nimport auto from './${base}.auto.js';\nimport touch from './${base}.touch.js';\nimport { mergeSpecs } from '${relImport(specsDir, path.join(ROOT, 'scenes/lib/director/staging/merge.js'))}';\n\nexport default mergeSpecs(auto, touch);\n`);
    // an episode with its own continuity (engine/setgen: final/continuity.js) passes it to the set scene (phase 7)
    const contFile = path.join(path.dirname(scenesDir), 'continuity.js');
    const withCont = fs.existsSync(contFile);
    const stageJs = relImport(scenesDir, path.join(ROOT, withCont ? 'scenes/lib/director/staging/set-scene.js' : 'scenes/lib/director/stage.js'));
    const builderJs = relImport(scenesDir, path.join(ROOT, `scenes/lib/director/sets/${base}.js`));
    files.set(path.join(scenesDir, reg.file), { once: true, text: `// Set scene - ${setId} for ${ep} (${GEN}, created once): the shot director's set scene, the Episode 1 pattern.\n//   node render/render.mjs ${path.relative(ROOT, path.join(scenesDir, reg.file)).split(path.sep).join('/')} --preset draft --start <start_s> --seconds <frames/24>\nimport { createSetScene } from '${stageJs}';\nimport * as builder from '${builderJs}';\nimport spec from './specs/${base}.spec.js';\n${withCont ? "import continuity from '../continuity.js';\n" : ''}\nconst S = createSetScene({ set: '${setId}', builder, spec, table: new URL('./${reg.file.replace(/\.js$/, '.shots.json')}', import.meta.url).href, title: ${JSON.stringify(title || `${ep.toUpperCase()} - ${setId}`)}${withCont ? ', continuity' : ''} });\nexport const meta = S.meta;\nexport async function setup(ctx) { await S.setup(ctx); }\nexport function update(t, ctx) { S.update(t, ctx); }\n` });
  }
  return { files, reports };
}

export function reportText(ep, reports) {
  const md = [`# Stage report - ${ep}`, '', `Generated by \`engine/stager/write.mjs\` (stager v${STAGER_VERSION}). A FLAG means: look at the still, touch up in \`<set>.touch.js\`.`, '',
    '| shot | template | score | tries | fixes | flags | unstaged |', '|---|---|---:|---:|---|---|---|'];
  for (const r of reports) md.push(`| ${r.id} | ${r.template ?? '-'} | ${r.score ?? '-'} | ${r.tries ?? 0} | ${(r.fixes || []).join(', ')} | ${(r.flags || []).join('; ')} | ${(r.unstaged || []).join('; ').replace(/\|/g, '/')} |`);
  const flagged = reports.filter((r) => (r.flags || []).some((f) => /^(FLAG|E_)/.test(f)));
  md.push('', `${reports.length} shots, ${flagged.length} flagged.`);
  return md.join('\n') + '\n';
}

async function main() {
  const { ep, argv } = episodeArg(process.argv.slice(2), null);
  if (!ep) throw new Error('--episode <id> is required (e.g. t00)');
  const opt = (n) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : null; };
  const CHECK = argv.includes('--check');
  const D = dirs(ep);
  const out = opt('--out') ? path.resolve(opt('--out')) : null;
  if (ep === 's01e01' && !out) throw new Error('s01e01 is hand-staged: its specs are never written (use --out <scratch dir> to re-stage into a scratch folder)');
  const finalDir = out || D.final;
  const scenesDir = out ? path.join(out, 'scenes') : D.scenes;
  const shotlist = JSON.parse(fs.readFileSync(D.shotlist, 'utf8'));
  const sets = opt('--sets') ? opt('--sets').split(',') : null;
  const rows = shotlist.shots.filter((s) => s.render !== 'black' && (!sets || sets.includes(s.set)));
  const lockF = path.join(D.final, 'cast.lock.json');
  const castLock = fs.existsSync(lockF) && ep !== 's01e01' ? JSON.parse(fs.readFileSync(lockF, 'utf8')) : null;
  const cfg = episodeConfig(ep) || {};
  const { files, reports } = stageEpisode(ep, rows, { scenesDir, castLock, faces: cfg.faces || 'avoid', title: cfg.title ? `${ep.toUpperCase()} - ${cfg.title}` : null });
  files.set(path.join(finalDir, 'stage-report.json'), JSON.stringify({ episode: ep, stager: STAGER_VERSION, generated_by: 'engine/stager/write.mjs', shots: reports.map(({ checks, ...r }) => r) }, null, 1) + '\n');
  files.set(path.join(finalDir, 'stage-report.md'), reportText(ep, reports));
  let changed = 0;
  for (const [f, v] of files) {
    const once = typeof v === 'object';
    const text = once ? v.text : v;
    const old = fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : null;
    if (once && old != null) continue;                                     // touch.js / the scene file: never rewritten
    if (old === text) continue;
    if (old != null && f.endsWith('.spec.js') && !old.includes(GEN)) throw new Error(`${path.relative(ROOT, f)} is hand-written: refusing to overwrite it`);
    changed++;
    if (CHECK) { console.log(`out of date: ${path.relative(ROOT, f)}`); continue; }
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, text);
    console.log(`wrote ${path.relative(ROOT, f)}`);
  }
  for (const r of reports) console.log(`${r.id} ${r.template} score ${r.score}${r.flags?.length ? ` | ${r.flags.join('; ')}` : ''}`);
  if (CHECK && changed) process.exit(1);
}
if (import.meta.url === pathToFileURL(process.argv[1] || '').href) main().catch((e) => { console.error(e.message || e); process.exit(1); });
