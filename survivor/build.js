function build() {
  const files = fs.readdirSync(SRC).filter((f) => f.endsWith('.js')).sort();
  if (!files.length) throw new Error('no sources found in survivor/src');

  const parts = files.map((f) => {
    const body = fs.readFileSync(path.join(SRC, f), 'utf8');
    if (/^\s*(import|export)\s/m.test(body)) {
      throw new Error(`${f} uses import/export — survivor sources must be plain scripts`);
    }
    return `\n/* ─────────── ${f} ─────────── */\n${body}`;
  });

  const banner = `/*!
 * Survivor v${VERSION}
 * The simulation layer: physiology, disease, ballistics, ecology, terrain.
 * Runs on the Legend Engine — https://github.com/dax-code-bro/untitled-new-game-project
 * Generated by survivor/build.js — edit survivor/src/*.js, not this file.
 */`;

  const bundle = `${banner}
(function (global) {
'use strict';
${parts.join('\n')}

/* ─────────── public surface ─────────── */
const Survivor = {
  version: '${VERSION}',
${EXPORTS.map((e) => `  ${e},`).join('\n')}
};

global.Survivor = Survivor;
global.SV = global.SV || Survivor;
if (typeof module !== 'undefined' && module.exports) module.exports = Survivor;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, bundle);

  // Compile without executing, so a syntax error or a missing export surfaces
  // here rather than in the browser console.
  try {
    // eslint-disable-next-line no-new-func
    new Function(bundle);
  } catch (err) {
    throw new Error(`bundle has a syntax error: ${err.message}`);
  }

  const kb = (Buffer.byteLength(bundle) / 1024).toFixed(1);
  console.log(`survivor.js  ${kb} KB  from ${files.length} modules  (v${VERSION})`);
  return bundle;
}

if (process.argv.includes('--watch')) {
  build();
  fs.watch(SRC, () => { try { build(); } catch (e) { console.error(e.message); } });
  console.log('watching survivor/src …');
} else {
  build();
}
