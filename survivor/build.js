#!/usr/bin/env node
/* Bundles survivor/src/*.js into site/survivor/survivor.js.
 *
 * Same approach as the engine build, and for the same reason: the sources
 * are plain scripts concatenated inside one IIFE so they share a lexical
 * scope, which keeps the whole game two <script> tags with no bundler, no
 * import map and no CORS story.
 *
 * Usage:  node survivor/build.js [--watch]
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(__dirname, 'src');
const OUT = path.join(ROOT, 'site', 'survivor', 'survivor.js');
const VERSION = require('./version.json').version;

/* Everything the game exposes. Kept explicit rather than generated, so that
   adding something to the public surface is a decision rather than an
   accident of where a `const` happened to be written. */
